"""Write demo/apple2c_demo.apple2c, the PureMetal Apple IIc demo, with its tables and the drawing code
generated here (all PureMetal; no ASM):

  - a rainbow of ten lo-res colours flowing diagonally across 20 rows, drawn on the text page that is
    not shown, then the pages swap;
  - a title and a scrolling message in the four text lines under it (mixed mode);
  - Ode to Joy (Beethoven, public domain) on the one-bit speaker: a quarter of a note's slice after
    each quarter of the frame is drawn, so the gaps in the tone stay short.

Why the drawing is generated: with a constant row address, `PokeA($0480 + x, PeekA(?comb + j))`
compiles to `lda comb,y` / `sta $0480,y` (about 60 cycles a byte); with a computed row address it is
three times that. So each of the 20 rows x 2 pages gets its own short loop.

The speaker loop was measured on this repository's machine (tools: apple2c_check --click-times): a
click every 45.9 x delay + 178 cycles.

    py -3 demo/make_demo.py
then build with PureMetalForge (compiler 9b5dfd993 or later): --compile demo/apple2c_demo.apple2c -o demo/apple2c_demo.hex
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLOCK = 1020484
PER, OVERHEAD = 45.9, 178          # cycles: a click every PER * delay + OVERHEAD
QUARTER = 16000                    # cycles of tone after each quarter of a frame

SEQ = [1, 11, 9, 13, 12, 14, 7, 6, 2, 3]   # magenta pink orange yellow green aqua light-blue blue dark-blue purple
COMB = [SEQ[i % 10] | (SEQ[(i + 1) % 10] << 4) for i in range(72)]

FREQ = {'G3': 196.0, 'C4': 261.63, 'D4': 293.66, 'E4': 329.63, 'F4': 349.23, 'G4': 392.0}
TUNE = ("E4 2 E4 2 F4 2 G4 2 G4 2 F4 2 E4 2 D4 2 C4 2 C4 2 D4 2 E4 2 E4 3 D4 1 D4 4 "
        "E4 2 E4 2 F4 2 G4 2 G4 2 F4 2 E4 2 D4 2 C4 2 C4 2 D4 2 E4 2 D4 3 C4 1 C4 4 "
        "D4 2 D4 2 E4 2 C4 2 D4 2 E4 1 F4 1 E4 2 C4 2 D4 2 E4 1 F4 1 E4 2 D4 2 C4 2 D4 2 G3 4 "
        "E4 2 E4 2 F4 2 G4 2 G4 2 F4 2 E4 2 D4 2 C4 2 C4 2 D4 2 E4 2 D4 3 C4 1 C4 4 R 4").split()

TITLE = "     PUREMETAL  *  APPLE IIC  DEMO      "
MESSAGE = ("     PUREMETAL ON THE APPLE IIC  ...  A 65C02 PROGRAM COMPILED FROM BASIC-STYLE SOURCE, BOOTING "
           "FROM ITS OWN DISK  ...  THE SAME DISK RUNS ON A PICO W, A PICO 2 W AND THE PC  ...  ODE TO JOY, "
           "BEETHOVEN, ON THE ONE-BIT SPEAKER  ...  ")

def text_row(r, page):
    return 0x400 * page + (r & 7) * 0x80 + (r >> 3) * 0x28

def notes():
    out = []
    for i in range(0, len(TUNE), 2):
        name, frames = TUNE[i], int(TUNE[i + 1])
        if name == 'R':
            out.append((0, 0, frames))
            continue
        half = CLOCK / (2 * FREQ[name])
        delay = round((half - OVERHEAD) / PER)
        out.append((delay, round(QUARTER / (PER * delay + OVERHEAD)), frames))
    return out

def data(label, values):
    lines = [f'  {label}:']
    for s in range(0, len(values), 16):
        lines.append('  Data.a ' + ', '.join(f'${v:02X}' for v in values[s:s + 16]))
    return lines

def text(label, s):
    return data(label, [ord(c) | 0x80 for c in s])

def draw_procs():
    out = []
    for page in (1, 2):
        for chunk in range(4):
            out.append(f'; rows {chunk * 5}-{chunk * 5 + 4} of text page {page}')
            out.append(f'Procedure Draw{page}{chunk}()')
            for r in range(chunk * 5, chunk * 5 + 5):
                out.append(f'  j = k + {r}')
                out.append(f'  For x = 0 To 39')
                out.append(f'    PokeA(${text_row(r, page):04X} + x, PeekA(?comb + j))')
                out.append(f'    j = j + 1')
                out.append(f'  Next')
            out.append('EndProcedure')
            out.append('')
    return '\n'.join(out)

def main():
    assert len(TITLE) == 40
    tune = notes()
    src = f'''; PureMetal on the Apple IIc: a rainbow of the lo-res colours flowing across the screen, a scrolling
; message in the four text lines under it, and Ode to Joy (Beethoven) on the one-bit speaker.
; GENERATED by demo/make_demo.py - edit that, then run it.
;
; Build it as an .apple2c file: the compiler writes apple2c_demo.dsk, a disk that boots and runs it.
; The picture is drawn on the text page that is not shown, then the pages swap (PAGE1 $0400, PAGE2
; $0800), so it never tears. The speaker has no sound chip behind it: a tone is the program clicking
; $C030 with a delay loop between clicks, a quarter of the note after each quarter of the frame.

#MSG_LEN = {len(MESSAGE)}
#NOTES = {len(tune)}

Global page.a, t.a, k.a, j.a, x.a, scroll.u, note.a, left.a, click.a, cut.a

; count clicks of the speaker with delay between them; delay 0 is the same time, quiet
Procedure Tone(delay.a, count.a)
  Protected i.a, d.a
  If delay = 0
    For i = 1 To count
      For d = 1 To 39
      Next
    Next
  Else
    For i = 1 To count
      click = PeekA($C030)
      For d = 1 To delay
      Next
    Next
  EndIf
EndProcedure

Procedure Quarter()
  Tone(PeekA(?tunedelay + note), PeekA(?tunecount + note))
EndProcedure

{draw_procs()}
; the title on text row 20 and 40 characters of the message on row 22, on the page at off
Procedure DrawText(off.u)
  Protected base.u, s.u
  base = $0650 + off
  For x = 0 To 39
    PokeA(base + x, PeekA(?title + x))
  Next
  base = $0750 + off
  s = scroll
  For x = 0 To 39
    PokeA(base + x, PeekA(?message + s))
    s = s + 1
    If s >= #MSG_LEN
      s = 0
    EndIf
  Next
EndProcedure

Procedure ClearText(off.u)
  Protected r.a, base.u
  For r = 0 To 3
    base = PeekA(?textrow + r) + (PeekA(?textrowhi + r) << 8) + off
    For x = 0 To 39
      PokeA(base + x, $A0)
    Next
  Next
EndProcedure

Procedure Main()
  PokeA($C000, 0)                       ; 80STORE off: PAGE2 shows page 2
  PokeA($C00C, 0)                       ; 40 columns
  PokeA($C00E, 0)                       ; the primary character set
  ClearText($0000)
  ClearText($0400)
  click = PeekA($C056)                  ; lo-res
  click = PeekA($C053)                  ; four lines of text under it
  click = PeekA($C050)                  ; graphics on
  note = 0
  left = PeekA(?tunelen)
  Repeat
    k = t
    If page = 0                         ; page 1 is shown: draw page 2
      Draw20() : Quarter()
      Draw21() : Quarter()
      Draw22() : Quarter()
      Draw23() : Quarter()
      DrawText($0400)
      click = PeekA($C055)
      page = 1
    Else
      Draw10() : Quarter()
      Draw11() : Quarter()
      Draw12() : Quarter()
      Draw13() : Quarter()
      DrawText($0000)
      click = PeekA($C054)
      page = 0
    EndIf
    t = t + 1
    If t >= 10
      t = 0
    EndIf
    cut = cut + 1
    If cut >= 2                         ; the message moves a character every second frame
      cut = 0
      scroll = scroll + 1
      If scroll >= #MSG_LEN
        scroll = 0
      EndIf
    EndIf
    left = left - 1
    If left = 0
      note = note + 1
      If note >= #NOTES
        note = 0
      EndIf
      left = PeekA(?tunelen + note)
    EndIf
  ForEver
EndProcedure

Main()

DataSection
''' + '\n'.join(data('comb', COMB)
                + data('textrow', [text_row(r, 1) & 255 for r in range(20, 24)])
                + data('textrowhi', [text_row(r, 1) >> 8 for r in range(20, 24)])
                + data('tunedelay', [n[0] for n in tune])
                + data('tunecount', [n[1] for n in tune])
                + data('tunelen', [n[2] for n in tune])
                + text('title', TITLE) + text('message', MESSAGE)) + '''
EndDataSection
'''
    assert text_row(20, 1) == 0x650 and text_row(22, 1) == 0x750
    (HERE / 'apple2c_demo.apple2c').write_text(src)
    print(f'demo: {len(tune)} notes, message {len(MESSAGE)} characters')

if __name__ == '__main__':
    main()
