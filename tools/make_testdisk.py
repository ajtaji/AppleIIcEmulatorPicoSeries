"""This project's own test disk (no Apple code): a DOS-order 140 KB .dsk whose track 0 physical sector 0
holds a boot program, and every other sector a known pattern (byte i of physical sector s of track t
is (t * 16 + s + i) & 255). Booted from the test ROM (key D), the program reads all 544 sectors of
tracks 1-34 through the test ROM's own sector reader, checks each against the pattern and prints
    DISK READ TEST: 544 SECTORS PASS
on line 15 (or FAILED). It proves the drive's stepping, the nibblizer and the 6-and-2 path end to end.

Writes build/testdisk.dsk and build/testdisk_data.pmi (the diagnostic firmware's A2DiskData).
    py -3 tools/make_testdisk.py
"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from asm65 import assemble
from lzpack import pack_image

DOS_ORDER = [0, 7, 14, 6, 13, 5, 12, 4, 11, 3, 10, 2, 9, 1, 8, 15]

BOOT = r'''
ROW    = $02
COL    = $03
WTRK   = $11
WSEC   = $12
DEST   = $13
OKLO   = $20
OKHI   = $21
BAD    = $22
EXP    = $23
READSEC = $CF00
PRINT  = $CF03
LOOP   = $CF06

        .org $0800
        .byte 1
START:  lda #14
        sta ROW
        lda #0
        sta COL
        lda #<MSG1
        ldx #>MSG1
        jsr PRINT
        stz OKLO
        stz OKHI
        stz BAD
        lda #1
        sta WTRK
TRK:    stz WSEC
SEC:    stz DEST
        lda #$10
        sta DEST+1
        jsr READSEC
        bcs FAIL
        lda WTRK
        asl a
        asl a
        asl a
        asl a
        clc
        adc WSEC
        sta EXP
        ldy #0
V1:     tya
        clc
        adc EXP
        cmp (DEST),y
        bne FAIL
        iny
        bne V1
        inc OKLO
        bne NEXT
        inc OKHI
        bra NEXT
FAIL:   inc BAD
NEXT:   inc WSEC
        lda WSEC
        cmp #16
        bne SEC
        inc WTRK
        lda WTRK
        cmp #35
        bne TRK
        lda $C0E8            ; the motor off
        lda #15
        sta ROW
        lda #0
        sta COL
        lda BAD
        bne SAYBAD
        lda OKLO
        cmp #<544
        bne SAYBAD
        lda OKHI
        cmp #>544
        bne SAYBAD
        lda #<MSGOK
        ldx #>MSGOK
        jsr PRINT
        jmp LOOP
SAYBAD: lda #<MSGBAD
        ldx #>MSGBAD
        jsr PRINT
        jmp LOOP
MSG1:   .text "BOOTED: OUR SECTOR 0. READING 1-34"
        .byte 0
MSGOK:  .text "DISK READ TEST: 544 SECTORS PASS"
        .byte 0
MSGBAD: .text "DISK READ TEST: FAILED"
        .byte 0
'''

def main():
    lo, boot, labels, listing = assemble(BOOT)
    assert lo == 0x800 and len(boot) <= 256, len(boot)
    boot = boot + bytes(256 - len(boot))
    img = bytearray(143360)
    for t in range(35):
        for p in range(16):
            if t == 0 and p == 0:
                data = boot
            else:
                data = bytes(((t * 16 + p + i) & 255) for i in range(256))
            off = (t * 16 + DOS_ORDER[p]) * 256
            img[off:off + 256] = data
    (ROOT / 'build').mkdir(exist_ok=True)
    (ROOT / 'build/testdisk.dsk').write_bytes(img)
    packed = pack_image(bytes(img), 4096)
    lines = ['; Generated by tools/make_testdisk.py: this project\'s own test disk (no Apple code),',
             '; packed a track at a time (tools/lzpack.py).',
             '#A2_DISK_KIND = 1', 'DataSection', 'A2DiskData:']
    for s in range(0, len(packed), 32):
        lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in packed[s:s + 32]))
    lines.append('EndDataSection')
    (ROOT / 'build/testdisk_data.pmi').write_text('\n'.join(lines) + '\n')
    print(f'test disk: boot program {len(listing.splitlines())} lines, build/testdisk.dsk')

if __name__ == '__main__':
    main()
