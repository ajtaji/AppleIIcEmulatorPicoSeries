glyphs = []
for code in range(0x20, 0x80):
    rows = ['.' + r + '.' for r in G[chr(code)]] + ['.......']
    glyphs.append(rows)
for name, rows in M:
    assert len(rows) == 8 and all(len(r) == 7 for r in rows), name
    glyphs.append(rows)
data = bytearray()
for rows in glyphs:
    for r in rows:
        data.append(sum(1 << i for i, c in enumerate(r) if c == '#'))
lines = ['; Generated by tools/make_font.py: this project\'s own Apple IIc character set (not Apple\'s ROM).',
         '; 128 glyphs x 8 rows; glyph n < 96 = ASCII $20 + n, 96-127 = MouseText $40-$5F; bit 0 = leftmost dot.',
         'DataSection', 'A2Font:']
for s in range(0, len(data), 16):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in data[s:s + 16]))
lines.append('EndDataSection')
root = Path(__file__).resolve().parents[1]
(root / 'src/font.pmi').write_text('\n'.join(lines) + '\n')
(root / 'desktop').mkdir(exist_ok=True)
