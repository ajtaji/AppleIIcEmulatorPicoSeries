"""Put the board's CPU check data into Diagnostics/test_data.pmi (it stays in flash):
   Vectors       the first PER_OP vectors of every opcode from vectors_full.bin's source
   KlausC02 / Klaus02  bytes $0000-$3FFF of each Klaus Dormann image, then its last 16
                 bytes ($FFF0-$FFFF); everything between is one fill byte (checked here)."""
import struct, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from ss_load import load
from make_vectors import record, SRC

PER_OP = 12
blob, count = bytearray(), 0
for op in range(256):
    for t in load(SRC, op)[:PER_OP]:
        blob += record(t); count += 1
lines = ['; Generated by tools/embed_tests.py. Board CPU-check data; it stays in flash.',
         f'#VECTOR_COUNT = {count}', 'DataSection']
def emit(label, data):
    lines.append(label + ':')
    for s in range(0, len(data), 32):
        lines.append('  Data.a ' + ','.join(f'${x:02X}' for x in data[s:s + 32]))
emit('Vectors', blob)
for label, name in (('KlausC02', '65C02_extended_opcodes_test.bin'), ('Klaus02', '6502_functional_test.bin')):
    d = (ROOT / 'Diagnostics' / name).read_bytes()
    fill = d[0x4000]
    assert all(b == fill for b in d[0x4000:0xFFF0]), name
    emit(label, d[:0x4000] + d[0xFFF0:] + bytes([fill, 0, 0, 0]))
lines.append('EndDataSection')
(ROOT / 'Diagnostics/test_data.pmi').write_text('\n'.join(lines) + '\n')
print(count, 'vectors,', len(blob), 'bytes')
