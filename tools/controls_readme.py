"""The README's Controls section, from desktop/controls.pbi - the table the keyboard code and the Controls
tab read - so the three cannot disagree.

    py -3 tools/controls_readme.py          rewrite the section between the markers in README.md
    py -3 tools/controls_readme.py --check  exit 1 if README.md's section is not what the table gives
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / 'desktop' / 'controls.pbi'
README = ROOT / 'README.md'
BEGIN = '<!-- controls: generated by tools/controls_readme.py from desktop/controls.pbi -->'
END = '<!-- controls end -->'

# CtlAdd(#KIND, vk, "pc", "apple"[, value, mods, window]) - PureBasic strings have no escapes
ROW = re.compile(r'^\s*CtlAdd\(#(CTL_\w+),\s*[^,]+,\s*"([^"]*)",\s*"([^"]*)"', re.M)


def group(kind, pc):
    if kind == 'CTL_SHORTCUT':
        return 'The window'
    if 'Joystick' in pc:
        return 'Joystick'
    return 'Apple IIc keyboard'


def md(s):
    return s.replace('\\', '\\\\').replace('|', '\\|').replace('`', '\\`')


def section():
    rows = ROW.findall(TABLE.read_text(encoding='utf-8'))
    lines = [BEGIN, '']
    for title in ('Apple IIc keyboard', 'Joystick', 'The window'):
        lines += ['| ' + title + ' | |', '|---|---|']
        lines += ['| ' + md(pc) + ' | ' + md(a2) + ' |' for k, pc, a2 in rows if group(k, pc) == title]
        lines.append('')
    lines.append(END)
    return '\n'.join(lines)


def main():
    raw = README.read_bytes().decode('utf-8')
    crlf = '\r\n' in raw
    text = raw.replace('\r\n', '\n')
    i, j = text.index(BEGIN), text.index(END) + len(END)
    new = text[:i] + section() + text[j:]
    if '--check' in sys.argv:
        if new != text:
            print('README.md: the Controls section differs from desktop/controls.pbi - run tools/controls_readme.py')
            return 1
        print('README.md: the Controls section matches desktop/controls.pbi')
        return 0
    README.write_bytes((new.replace('\n', '\r\n') if crlf else new).encode('utf-8'))
    print('README.md: the Controls section written from desktop/controls.pbi')
    return 0


if __name__ == '__main__':
    sys.exit(main())
