"""Pack a disk image of our own (no Apple code) into a .pmi DataSection for a diagnostic firmware:
    py -3 tools/pack_disk.py demo/apple2c_demo.dsk build/demo_disk.pmi
A2DiskData in the tools/lzpack.py format, #A2_DISK_KIND from the extension (.dsk/.do 1, .po 2, .nib 3).
Apple's disks and anything private go through tools/make_private.py into private/ instead."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from lzpack import pack_image

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
d = src.read_bytes()
kind = {'.po': 2, '.nib': 3}.get(src.suffix.lower(), 1)
packed = pack_image(d, 6656 if kind == 3 else 4096)
lines = [f'; Generated by tools/pack_disk.py from {src.name}, packed a track at a time.',
         f'#A2_DISK_KIND = {kind}', 'DataSection', 'A2DiskData:']
for s in range(0, len(packed), 32):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in packed[s:s + 32]))
lines.append('EndDataSection')
dst.parent.mkdir(exist_ok=True)
dst.write_text('\n'.join(lines) + '\n')
print(f'{src}: {len(d)} bytes, packed {len(packed)} -> {dst}')
